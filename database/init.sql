
CREATE TABLE captures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename VARCHAR(255) NOT NULL,
    file_size BIGINT NOT NULL,
    total_packets BIGINT NOT NULL,
    total_bytes BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL,
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL
        DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE protocol_statistics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capture_id BIGINT NOT NULL,
    protocol VARCHAR(30) NOT NULL,
    packet_count BIGINT NOT NULL,

    CONSTRAINT fk_protocol_capture
        FOREIGN KEY (capture_id)
        REFERENCES captures(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_capture_protocol
        UNIQUE (capture_id, protocol)
);

CREATE TABLE network_flows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capture_id BIGINT NOT NULL,
    source_ip VARCHAR(45) NOT NULL,
    destination_ip VARCHAR(45) NOT NULL,
    source_port INTEGER,
    destination_port INTEGER,
    protocol VARCHAR(30) NOT NULL,
    packet_count BIGINT NOT NULL,
    total_bytes BIGINT NOT NULL,
    first_seen TIMESTAMP WITH TIME ZONE,
    last_seen TIMESTAMP WITH TIME ZONE,

    CONSTRAINT fk_flow_capture
        FOREIGN KEY (capture_id)
        REFERENCES captures(id)
        ON DELETE CASCADE
);

CREATE INDEX idx_flows_capture
    ON network_flows(capture_id);

CREATE INDEX idx_flows_source_ip
    ON network_flows(source_ip);

CREATE INDEX idx_flows_destination_ip
    ON network_flows(destination_ip);
